// ─── Helper Functions ─────────────────────────────────────────────────────────

export const getToolsByCategory = (categoryId: string): Tool[] =>
  TOOLS.filter((t) => t.category === categoryId);

export const getToolBySlug = (slug: string): Tool | undefined =>
  TOOLS.find((t) => t.slug === slug);

export const getFeaturedTools = (): Tool[] =>
  TOOLS.filter((t) => t.isFeatured && t.status === 'live');

export const getCategoryById = (id: string): ToolCategory_ | undefined =>
  CATEGORIES.find((c) => c.id === id);

export const getLiveTools = (): Tool[] =>
  TOOLS.filter((t) => t.status === 'live');

export const getRelatedTools = (toolId: string): Tool[] => {
  const tool = TOOLS.find((t) => t.id === toolId);
  if (!tool?.relatedTools) return [];
  return tool.relatedTools
    .map((id) => TOOLS.find((t) => t.id === id))
    .filter(Boolean) as Tool[];
};
